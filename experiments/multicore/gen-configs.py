#!/usr/bin/env python3
"""Fat-tree scaling configs: k x workers x {pure Days, P4-Days}.

The question these answer is the one the paper turns on -- does putting BMv2
inside Days keep Days' parallelism? -- so pure Days and P4-Days are generated
as a pair for every point, and the two curves are drawn together.

k is capped at 32. Each P4 switch owns a BMv2 instance and they cost about
10.2 MB each, measured: k=32 is 1,280 switches and 13.4 GB, which fits in 31 GB;
k=64 would be 5,120 switches and about 51 GB, which does not.
"""
import argparse, pathlib

def fat_tree(k):
    edge = agg = k * k // 2
    core = (k // 2) ** 2
    return edge + agg + core, k ** 3 // 4

TPL = """# Fat-tree k={k}, {workers} worker(s), {kind}.
#
# GENERATED by gen-configs.py -- do not edit.
#
# {switches} switches ({hosts} hosts). Every switch runs a pipeline in the P4
# variant, so each packet crosses several and different switches can run at the
# same time. The pure variant is the same network with no P4 at all: the two are
# a pair, and the point is whether the second scales like the first.
seed = 1000
threading = "multiple"
num_threads = {workers}
concurrency_level = "accelerated"
hot_workers = 2
log_path = "logs/scale/{name}"

[topology]
    category = "FatTree"

[topology.fat_tree]
    k = {k}

[switch]
    port_rate = 320000
    capacity = 100
    weights = [1]
    discipline = "FIFO"
    drop = "TailDrop"

{p4}[[flow_set]]
    flow_type = "PacketDistribution"
    flow_count = {flows}
    routing = "ECMP"
    [flow_set.traffic]
        initial_delay = 1.0
        duration = {duration}
        arr_dist = {{type = "Uniform", low = 1, high = 1}}
        pkt_size_dist = {{type = "Uniform", low = 1000, high = 1000}}
"""

P4 = """[p4]
    switches = [{sw}]
    program = "{program}"
    table = "MyIngress.flow_forward"
    action = "MyIngress.forward"
    log_events = false

"""

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(pathlib.Path(__file__).parent / "configs"))
    ap.add_argument("--program",
                    default=str(pathlib.Path(__file__).resolve().parents[2]
                                / "p4-programs/flow_route/flow_route.json"))
    ap.add_argument("--ks", default="8,16,32")
    ap.add_argument("--workers", default="1,2,4,8,16")
    ap.add_argument("--target-packets", type=int, default=3_000_000,
                    help="packets per run, held roughly constant across k by "
                         "setting the flow duration; see note below")
    args = ap.parse_args()

    out = pathlib.Path(args.out); out.mkdir(parents=True, exist_ok=True)
    print(f"{'k':>3} {'switches':>9} {'hosts':>7} {'flows':>7} "
          f"{'duration':>9} {'packets':>12}")
    for k in (int(x) for x in args.ks.split(",")):
        switches, hosts = fat_tree(k)
        # enough flows that there is work to spread; four per host at k=8 down
        # to a fraction at k=32, where the switch count already provides it
        flows = min(4096, max(256, switches * 4))
        # One packet per flow per simulated second, so duration is the packet
        # count per flow. Held so that every k moves about the same number of
        # packets: otherwise k=8 finishes in 0.2 s, where process start-up and
        # topology construction are most of the measurement and a speedup
        # number means nothing.
        duration = max(100, round(args.target_packets / flows))
        print(f"{k:>3} {switches:>9,} {hosts:>7,} {flows:>7,} {duration:>9,}"
              f" {flows * duration:>12,}")
        sw = ",".join(str(i) for i in range(switches))
        for w in (int(x) for x in args.workers.split(",")):
            for kind in ("pure", "p4"):
                name = f"k{k}_{kind}_w{w}"
                body = TPL.format(k=k, workers=w, kind=kind, switches=switches,
                                  hosts=hosts, name=name, flows=flows,
                                  duration=duration,
                                  p4=P4.format(sw=sw, program=args.program)
                                     if kind == "p4" else "")
                (out / f"{name}.toml").write_text(body, encoding="utf-8")
    print(f"\n-> {out}")

if __name__ == "__main__":
    main()
