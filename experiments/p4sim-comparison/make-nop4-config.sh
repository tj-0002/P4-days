#!/usr/bin/env bash
# Writes the no-P4 twin of days_config.toml: the same topology, the same links,
# the same flows, with the [p4] section removed and nothing else touched.
#
# Generated rather than kept by hand, so the two cannot drift. A drifted baseline
# would report the cost of a configuration change as the cost of BMv2.
set -eu
cd "$(dirname "$0")"

python3 - <<'PY'
src = open('days_config.toml', encoding='utf-8').read()
out, dropping = [], False
for line in src.splitlines():
    if line.startswith('[p4]'):
        dropping = True
        continue
    # a new top-level or [[array]] table ends the section
    if dropping and line.startswith('['):
        dropping = False
    if not dropping:
        out.append(line)

text = '\n'.join(out)
text = text.replace('log_path = "logs/m4/days"', 'log_path = "logs/m4/nop4"')
header = ("# GENERATED by make-nop4-config.sh -- do not edit.\n"
          "# The baseline for the BMv2 overhead measurement: days_config.toml\n"
          "# with its [p4] section removed.\n")
open('days_config_nop4.toml', 'w', encoding='utf-8').write(header + text + '\n')
PY
grep -qE '^\[p4\]' days_config_nop4.toml && { echo "[p4] survived the strip" >&2; exit 1; }
echo "days_config_nop4.toml written"
